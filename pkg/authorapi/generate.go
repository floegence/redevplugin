// Package authorapi generates author bindings from the current manifest contract.
package authorapi

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"unicode"

	"github.com/floegence/redevplugin/v3/pkg/manifest"
)

type Source struct {
	Method  string `json:"method"`
	Pointer string `json:"pointer"`
	Symbol  string `json:"symbol"`
}

// Generate never executes author code or infers resource permissions.
// Manifest remains the single authority; output files can be checked for drift.
func Generate(raw []byte) (map[string][]byte, error) {
	m, canonical, err := manifest.DecodeAuthorCanonical(bytes.NewReader(raw))
	if err != nil {
		return nil, err
	}
	hash := sha256.Sum256(canonical)
	var ts, rs strings.Builder
	ts.WriteString(`// Generated by ReDevPlugin from manifest.json. Do not edit.
import { callPluginActionSync, callPluginActionOperation, callPluginActionStream, type PluginBridgeClient, type PluginBridgeRequestOptions, type PluginJSONObject, type PluginJSONValue, type PluginExecution, type PluginActionStream } from "@floegence/redevplugin-ui/plugin";

`)
	rs.WriteString(`// Generated by ReDevPlugin from manifest.json. Do not edit.
use redevplugin_worker_sdk::{WorkerRequest, WorkerResult, WorkerError};
use serde::{Serialize, Deserialize};

fn present<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>
where D: serde::Deserializer<'de>, T: Deserialize<'de> {
    T::deserialize(deserializer).map(Some)
}

`)
	sources := []Source{}
	symbols := map[string]bool{}
	for i, method := range m.Methods {
		symbol := symbolName(method.Method)
		if symbols[symbol] {
			return nil, fmt.Errorf("/methods/%d: generated symbol %q collides; rename one action", i, symbol)
		}
		symbols[symbol] = true
		sources = append(sources, Source{method.Method, fmt.Sprintf("/methods/%d", i), symbol})
		fmt.Fprintf(&ts, `export type Action%dRequest = %s;
export type Action%dResponse = %s;
`, i, typeScriptRoot(method.RequestSchema, fmt.Sprintf("Action%dRequest", i), &ts), i, typeScriptRoot(method.ResponseSchema, fmt.Sprintf("Action%dResponse", i), &ts))
		if method.Route.Kind == manifest.MethodRouteWorker {
			rustRoot(&rs, fmt.Sprintf("Action%dRequest", i), method.RequestSchema)
			rustRoot(&rs, fmt.Sprintf("Action%dResponse", i), method.ResponseSchema)
		}
	}
	ts.WriteString(`
export interface Actions {
`)
	for i, method := range m.Methods {
		fmt.Fprintf(&ts, `  %q: { request: Action%dRequest; response: Action%dResponse };
`, method.Method, i, i)
	}
	ts.WriteString(`}

export function createActions(bridge: PluginBridgeClient) {
  return Object.freeze({
`)
	for i, method := range m.Methods {
		mode, result, cancelable := "Sync", fmt.Sprintf("Action%dResponse", i), false
		if method.CancelPolicy != nil {
			cancelable = method.CancelPolicy.Cancelable
		}
		switch method.Execution {
		case manifest.MethodExecutionOperation:
			mode, result = "Operation", fmt.Sprintf("PluginExecution<Action%dResponse, %t>", i, cancelable)
		case manifest.MethodExecutionSubscription:
			mode, result = "Stream", fmt.Sprintf("PluginActionStream<Action%dResponse>", i)
		}
		generic := fmt.Sprintf("Action%dResponse", i)
		if mode == "Operation" {
			generic += fmt.Sprintf(", %t", cancelable)
		}
		fmt.Fprintf(&ts, `    %q: (request: Action%dRequest, options: PluginBridgeRequestOptions = {}): Promise<%s> => callPluginAction%s<%s>(bridge, { method: %q, execution: %q, cancelable: %t }, request as PluginJSONObject, options),
`, method.Method, i, result, mode, generic, method.Method, method.Execution, cancelable)
	}
	ts.WriteString(`  });
}

export interface SurfaceActions {
`)
	for i, method := range m.Methods {
		if method.Route.Kind == manifest.MethodRouteSurface {
			fmt.Fprintf(&ts, `  %q: { request: Action%dRequest; response: Action%dResponse };
`, method.Method, i, i)
		}
	}
	ts.WriteString(`}

export function registerAction<K extends keyof SurfaceActions>(bridge: PluginBridgeClient, name: K, handler: (request: SurfaceActions[K]["request"], context: { signal: AbortSignal }) => SurfaceActions[K]["response"] | Promise<SurfaceActions[K]["response"]>): Promise<() => Promise<void>> {
  return bridge.registerMethod(name, async (request, context) => await handler(request as SurfaceActions[K]["request"], context) as PluginJSONValue);
}
`)
	rs.WriteString(`pub trait WorkerActions {
`)
	for i, method := range m.Methods {
		if method.Route.Kind == manifest.MethodRouteWorker {
			fmt.Fprintf(&rs, `    fn %s(&mut self, request: Action%dRequest) -> Result<Action%dResponse, WorkerError>;
`, sources[i].Symbol, i, i)
		}
	}
	rs.WriteString(`}

pub fn dispatch(handler: &mut impl WorkerActions, request: WorkerRequest) -> WorkerResult {
    match request.method.as_str() {
`)
	for i, method := range m.Methods {
		if method.Route.Kind == manifest.MethodRouteWorker {
			fmt.Fprintf(&rs, `        %s => {
            let input: Action%dRequest = serde_json::from_value(request.params).map_err(|_| WorkerError::invalid_request("invalid action request"))?;
            serde_json::to_value(handler.%s(input)?).map_err(|_| WorkerError::invalid_request("invalid action response"))
        },
`, rustString(method.Method), i, sources[i].Symbol)
		}
	}
	rs.WriteString(`        _ => Err(WorkerError::invalid_request("unknown worker action")),
    }
}
`)
	mapping, _ := json.MarshalIndent(map[string]any{"manifest_sha256": hex.EncodeToString(hash[:]), "actions": sources}, "", "  ")
	return map[string][]byte{"manifest.json": append(canonical, '\n'), "actions.ts": []byte(ts.String()), "actions.rs": []byte(rs.String()), "source-map.json": append(mapping, '\n')}, nil
}

func symbolName(name string) string {
	var out strings.Builder
	out.WriteString(`action_`)
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			out.WriteRune(r)
		} else {
			out.WriteRune('_')
		}
	}
	return out.String()
}
func keys(m map[string]any) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
func required(schema map[string]any) map[string]bool {
	out := map[string]bool{}
	if a, ok := schema["required"].([]any); ok {
		for _, v := range a {
			if s, ok := v.(string); ok {
				out[s] = true
			}
		}
	}
	return out
}
func typeScriptRoot(schema map[string]any, prefix string, out *strings.Builder) string {
	defs, _ := schema["$defs"].(map[string]any)
	for _, name := range keys(defs) {
		fmt.Fprintf(out, "export type %s = %s;\n", definitionName(prefix, name), tsType(defs[name], prefix))
	}
	return tsType(schema, prefix)
}
func definitionName(prefix, name string) string {
	return prefix + "Def" + hex.EncodeToString([]byte(name))
}
func tsType(value any, prefix string) string {
	if v, ok := value.(bool); ok {
		if !v {
			return "never"
		}
		return "PluginJSONValue"
	}
	schema, ok := value.(map[string]any)
	if !ok {
		return "PluginJSONValue"
	}
	parts := []string{}
	if ref, ok := schema["$ref"].(string); ok {
		path := strings.TrimPrefix(ref, "#/$defs/")
		tokens := strings.Split(path, "/")
		name := strings.ReplaceAll(strings.ReplaceAll(tokens[0], "~1", "/"), "~0", "~")
		if strings.HasPrefix(ref, "#/$defs/") && len(tokens) == 1 {
			parts = append(parts, definitionName(prefix, name))
		} else {
			parts = append(parts, "PluginJSONValue")
		}
	}
	if value, ok := schema["const"]; ok {
		raw, _ := json.Marshal(value)
		parts = append(parts, string(raw))
	}
	if values, ok := schema["enum"].([]any); ok {
		valuesTS := []string{}
		for _, value := range values {
			raw, _ := json.Marshal(value)
			valuesTS = append(valuesTS, string(raw))
		}
		if len(valuesTS) > 0 {
			parts = append(parts, "("+strings.Join(valuesTS, " | ")+")")
		}
	}
	for _, key := range []string{"oneOf", "anyOf", "allOf"} {
		if branches, ok := schema[key].([]any); ok {
			types := []string{}
			for _, branch := range branches {
				types = append(types, "("+tsType(branch, prefix)+")")
			}
			separator := " | "
			if key == "allOf" {
				separator = " & "
			}
			if len(types) > 0 {
				parts = append(parts, "("+strings.Join(types, separator)+")")
			}
		}
	}
	if types, ok := schema["type"].([]any); ok {
		unions := []string{}
		for _, typ := range types {
			child := map[string]any{}
			for k, v := range schema {
				child[k] = v
			}
			child["type"] = typ
			unions = append(unions, tsType(child, prefix))
		}
		return "(" + strings.Join(unions, " | ") + ")"
	}
	typ, _ := schema["type"].(string)
	switch typ {
	case "string":
		parts = append(parts, "string")
	case "number", "integer":
		parts = append(parts, "number")
	case "boolean":
		parts = append(parts, "boolean")
	case "null":
		parts = append(parts, "null")
	case "array":
		parts = append(parts, "Array<"+tsType(schema["items"], prefix)+">")
	case "object":
		props, _ := schema["properties"].(map[string]any)
		req := required(schema)
		fields := []string{}
		for _, name := range keys(props) {
			optional := "?"
			if req[name] {
				optional = ""
			}
			raw, _ := json.Marshal(name)
			fields = append(fields, fmt.Sprintf("%s%s: %s", raw, optional, tsType(props[name], prefix)))
		}
		patterns, _ := schema["patternProperties"].(map[string]any)
		additional, closed := schema["additionalProperties"].(bool)
		if len(patterns) > 0 || !closed || additional {
			fields = append(fields, "[key: string]: PluginJSONValue | undefined")
		}
		if len(fields) == 0 {
			parts = append(parts, "Record<string, never>")
		} else {
			parts = append(parts, "{ "+strings.Join(fields, "; ")+" }")
		}
	}
	if len(parts) == 0 {
		return "PluginJSONValue"
	}
	return strings.Join(parts, " & ")
}

// Root compositions must retain every accepted field. The Host remains the
// schema validator; unsupported Rust shapes use a lossless JSON value.
func rustRoot(out *strings.Builder, name string, schema map[string]any) {
	typ := rustType(out, name, schema)
	if typ != name {
		fmt.Fprintf(out, "pub type %s = %s;\n\n", name, typ)
	}
}

func rustObject(out *strings.Builder, name string, schema map[string]any) {
	var fields strings.Builder
	props, _ := schema["properties"].(map[string]any)
	req := required(schema)
	symbols := map[string]bool{}
	for i, key := range keys(props) {
		child, _ := props[key].(map[string]any)
		typ := rustType(out, fmt.Sprintf("%sField%d", name, i), child)
		if !req[key] {
			typ = "Option<" + typ + ">"
			fields.WriteString(`    #[serde(default, deserialize_with = "present", skip_serializing_if = "Option::is_none")]
`)
		}
		symbol := rustField(key)
		for symbols[symbol] {
			symbol += "_"
		}
		symbols[symbol] = true
		fmt.Fprintf(&fields, `    #[serde(rename = %s)]
    pub r#%s: %s,
`, rustString(key), symbol, typ)
	}
	fmt.Fprintf(out, `#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct %s {
%s}

`, name, fields.String())
}
func rustType(out *strings.Builder, name string, schema map[string]any) string {
	for _, keyword := range []string{"$ref", "oneOf", "anyOf", "allOf", "patternProperties"} {
		if _, ok := schema[keyword]; ok {
			return "serde_json::Value"
		}
	}
	typ, _ := schema["type"].(string)
	switch typ {
	case "string":
		return "String"
	case "boolean":
		return "bool"
	case "integer":
		return "serde_json::Number"
	case "number":
		return "f64"
	case "array":
		child, _ := schema["items"].(map[string]any)
		return "Vec<" + rustType(out, name+"Item", child) + ">"
	case "object":
		if closed, ok := schema["additionalProperties"].(bool); !ok || closed {
			return "serde_json::Value"
		}
		rustObject(out, name, schema)
		return name
	default:
		return "serde_json::Value"
	}
}
func rustField(name string) string {
	if name == "" || name == "_" || name == "self" || name == "Self" || name == "super" || name == "crate" {
		return "field_" + hex.EncodeToString([]byte(name))
	}
	for i, r := range name {
		valid := r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9'
		if !valid {
			return "field_" + hex.EncodeToString([]byte(name))
		}
	}
	return name
}

func rustString(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, r := range value {
		switch r {
		case '"':
			out.WriteString(`\"`)
		case '\\':
			out.WriteString(`\\`)
		default:
			if r < 32 || r == 127 {
				fmt.Fprintf(&out, `\u{%x}`, r)
			} else {
				out.WriteRune(r)
			}
		}
	}
	out.WriteByte('"')
	return out.String()
}
