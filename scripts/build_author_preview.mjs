import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const result = await build({ entryPoints: [resolve(root, "internal/authorpreview/app.ts")], bundle: true, format: "esm", platform: "browser", target: "es2022", legalComments: "none", write: false });
const output = "// Code generated by scripts/build_author_preview.mjs; DO NOT EDIT.\n" + result.outputFiles[0].text;
const destination = resolve(root, "cmd/redevplugin/author_assets/app.js");
if (process.argv.includes("--check")) { if (await readFile(destination, "utf8") !== output) throw new Error("Author preview bundle is stale"); }
else await writeFile(destination, output);
