import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname,"..");
const result = await build({entryPoints:[resolve(root,"scripts/author_runtime_prepare.mjs")],bundle:true,format:"esm",platform:"node",target:"node26",write:false,legalComments:"none",banner:{js:'import { createRequire } from "node:module"; const require = createRequire(import.meta.url);'}});
const output = "// Code generated by scripts/build_author_runtime.mjs; DO NOT EDIT.\n" + result.outputFiles[0].text;
const destination = resolve(root,"cmd/redevplugin/author_assets/runtime-prepare.mjs");
if (process.argv.includes("--check")) { if (await readFile(destination,"utf8") !== output) throw new Error("Author runtime bundle is stale"); }
else await writeFile(destination,output);
