import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const schema = JSON.parse(await readFile(resolve(root, "spec/plugin/repository-index-v1.schema.json"), "utf8"));
const identity = JSON.parse(await readFile(resolve(root, "spec/plugin/repository-identity.schema.json"), "utf8"));
const sourceSchema = JSON.parse(await readFile(resolve(root, "spec/plugin/manifest-v9.schema.json"), "utf8"));
sourceSchema.$id = "https://schemas.redevplugin.dev/plugin-api/1/source-manifest.schema.json";
sourceSchema.title = "ReDevPlugin author source manifest";
sourceSchema.description = "Editable plugin source. Authors declare a repository-local slug; the platform compiles package identity before bindings, build and hashing. This document is not installable.";
sourceSchema.properties.schema_version = { const: "redevplugin.source.v1" };
sourceSchema.required = sourceSchema.required.filter((name) => name !== "publisher");
sourceSchema.properties.publisher.required = [];
delete sourceSchema.properties.publisher.properties.publisher_id;
sourceSchema.properties.plugin.required = sourceSchema.properties.plugin.required.map((name) => name === "plugin_id" ? "slug" : name);
delete sourceSchema.properties.plugin.properties.plugin_id;
sourceSchema.properties.plugin.properties.slug = { type: "string", minLength: 1, maxLength: 80, pattern: "^[a-z0-9]+(?:-[a-z0-9]+)*$" };
const sourceSchemaPath = resolve(root, "spec/plugin/source-manifest.schema.json");
const sourceJSON = JSON.stringify(sourceSchema, null, 2) + "\n";
if (process.argv.includes("--check")) {
 if (await readFile(sourceSchemaPath, "utf8").catch(() => "") !== sourceJSON) throw new Error("Source manifest schema is stale; run npm run repository-index:generate");
} else { await writeFile(sourceSchemaPath, sourceJSON); }
const output = `// Code generated by scripts/generate_repository_index.mjs; DO NOT EDIT.\n\nexport const repositoryIndexJSONSchema = ${JSON.stringify(schema, null, 2)} as const;\n\nexport const repositoryIdentityJSONSchema = ${JSON.stringify(identity, null, 2)} as const;\n\nexport const sourceManifestJSONSchema = ${JSON.stringify(sourceSchema, null, 2)} as const;\n`;
const path = resolve(root, "packages/redevplugin-contracts/src/repository-index.gen.ts");
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8").catch(() => "") !== output) throw new Error("repository index schema is stale; run npm run repository-index:generate");
} else {
  await writeFile(path, output);
}
