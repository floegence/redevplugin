import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parse } from "yaml";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const source = parse(await readFile(resolve(root, "spec/openapi/plugin-platform.yaml"), "utf8"));
const schemas = {};
const allowed = new Set(["type", "const", "enum", "properties", "required", "additionalProperties", "items", "minItems", "maxItems", "uniqueItems", "minLength", "maxLength", "minimum", "maximum", "pattern", "$ref"]);
function visit(name) {
  if (Object.hasOwn(schemas, name)) return;
  if (!source.components.schemas[name]) throw new Error(`Missing schema ${name}`);
  schemas[name] = {};
  schemas[name] = clean(source.components.schemas[name]);
}
function clean(schema) {
  if (schema.type === "object" && schema.additionalProperties !== false) throw new Error("Security summary objects must be closed");
  const result = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === "description" || key === "title") continue;
    if (!allowed.has(key)) throw new Error(`Unsupported summary schema keyword ${key}`);
    if (key === "$ref") {
      if (!value.startsWith("#/components/schemas/")) throw new Error(`Unsupported reference ${value}`);
      const name = value.slice("#/components/schemas/".length);
      visit(name); result.ref = name;
    } else if (key === "properties") {
      result.properties = Object.fromEntries(Object.entries(value).map(([field, child]) => [field, clean(child)]));
    } else if (key === "items") result.items = clean(value);
    else result[key] = value;
  }
  return result;
}
visit("ExternalPackageSecuritySummary");
function type(schema) {
  if (schema.ref) return schema.ref;
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ");
  if (schema.type === "object") return `{\n${Object.entries(schema.properties).map(([field, child]) => `  ${field}${schema.required.includes(field) ? "" : "?"}: ${type(child)};`).join("\n")}\n}`;
  if (schema.type === "array") return `Array<${type(schema.items)}>`;
  if (schema.type === "integer") return "number";
  if (["string", "boolean"].includes(schema.type)) return schema.type;
  throw new Error(`Unsupported summary type ${JSON.stringify(schema)}`);
}
const declarations = Object.entries(schemas).map(([name, schema]) => `export type ${name} = ${type(schema)};`).join("\n\n");
function jsonSchema(value) {
  if (Array.isArray(value)) return value.map(jsonSchema);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.entries(value).map(([key, child]) => key === "ref" ? ["$ref", `#/$defs/${child}`] : [key, jsonSchema(child)]));
}
const schema = { $schema: "https://json-schema.org/draft/2020-12/schema", $ref: "#/$defs/ExternalPackageSecuritySummary", $defs: jsonSchema(schemas) };
const output = `// Code generated by scripts/generate_security_summary.mjs; DO NOT EDIT.\n\n${declarations}\n\nexport const securitySummarySchemas = ${JSON.stringify(schemas, null, 2)} as const;\n\nexport const securitySummaryJSONSchema = ${JSON.stringify(schema, null, 2)} as const;\n`;
const files = new Map([
  ["packages/redevplugin-contracts/src/security-summary.gen.ts", output],
  ["testdata/contracts/security-summary-schema.json", JSON.stringify(schemas, null, 2) + "\n"],
]);
for (const [name, content] of files) {
  const path = resolve(root, name);
  if (check) {
    if (await readFile(path, "utf8").catch(() => "") !== content) throw new Error(`${name} is stale; run npm run security-summary:generate`);
  } else await writeFile(path, content);
}
