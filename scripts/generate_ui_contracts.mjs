#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { parse as parseYAML } from "yaml";

const root = resolve(import.meta.dirname, "..");
const checkOnly = process.argv.includes("--check");
const openAPIPath = join(root, "spec/openapi/plugin-platform.yaml");
const tsConstantsPath = join(root, "packages/redevplugin-ui/src/contracts.gen.ts");
const routesPath = join(root, "testdata/contracts/routes.json");

const pluginAPI = await readPluginAPI();
const outputs = new Map([
  [tsConstantsPath, renderTypeScriptConstants(pluginAPI)],
  [routesPath, await renderRoutes()],
]);

for (const [filename, content] of outputs) {
  if (checkOnly) {
    const current = await readFile(filename, "utf8").catch(() => "");
    if (current !== content) {
      throw new Error(`${relative(root, filename)} is stale; run npm run ui-contracts:generate`);
    }
  } else {
    await writeFile(filename, content);
  }
}

function renderTypeScriptConstants(pluginAPI) {
  return `// Code generated by scripts/generate_ui_contracts.mjs; DO NOT EDIT.\n\nexport const pluginAPIMajor = ${pluginAPI} as const;\n`;
}

async function readPluginAPI() {
  const source = JSON.parse(await readFile(join(root, "spec/plugin/plugin-api.json"), "utf8"));
  if (!isRecord(source) || !hasExactKeys(source, ["plugin_api"]) || !Number.isSafeInteger(source.plugin_api) || source.plugin_api < 1) {
    throw new Error("plugin API identity must contain one positive integer plugin_api");
  }
  return source.plugin_api;
}

async function renderRoutes() {
  const openAPI = parseYAML(await readFile(openAPIPath, "utf8"));
  if (!isRecord(openAPI) || !isRecord(openAPI.paths)) throw new Error("OpenAPI paths object is missing");
  const routes = [];
  for (const [path, pathItem] of Object.entries(openAPI.paths)) {
    if (!isRecord(pathItem)) continue;
    for (const method of ["delete", "get", "patch", "post", "put"]) {
      const operation = pathItem[method];
      if (!isRecord(operation)) continue;
      const effect = operation["x-redevplugin-route-effect"];
      if (effect !== "query" && effect !== "mutation") {
        throw new Error(`OpenAPI route ${method.toUpperCase()} ${path} has invalid or missing x-redevplugin-route-effect`);
      }
      routes.push({ method: method.toUpperCase(), path, effect });
    }
  }
  routes.sort((left, right) => left.path < right.path ? -1 : left.path > right.path ? 1 : left.method.localeCompare(right.method));
  return `${JSON.stringify(routes, null, 2)}\n`;
}

function hasExactKeys(value, expected) {
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  return actual.length === wanted.length && actual.every((key, index) => key === wanted[index]);
}

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
